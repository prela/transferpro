function minutesFromStart(ride: PrototypeRide): number {
  const [hour, minute] = ride.time.split(':').map(Number)
  const value = (hour ?? 0) * 60 + (minute ?? 0)
  return value < 6 * 60 ? value + 24 * 60 : value
}

export function ridesInOrder(rides: readonly PrototypeRide[]): PrototypeRide[] {
  return [...rides].sort((a, b) => minutesFromStart(a) - minutesFromStart(b))
}

export function todayRides(): PrototypeRide[] {
  return ridesInOrder(PROTOTYPE_RIDES.filter(ride => ride.day === 'today'))
}

