export function urgentRides(rides: readonly PrototypeRide[]): PrototypeRide[] {
  return ridesInOrder(rides.filter(ride => ride.urgent !== null))
}

export type HomeList = 'unassigned' | 'waiting' | 'inProgress'

/** A ride with an urgent item is only in Pozornost, so Home never shows it twice. */
export function homeList(ride: PrototypeRide): HomeList | null {
  if (ride.urgent)
    return null
  if (ride.state === 'unassigned')
    return 'unassigned'
  if (ride.state === 'assigned')
    return 'waiting'
  if (ride.state === 'in-progress')
    return 'inProgress'
  return null
}

export type DayFilter = 'all' | 'urgent' | 'warnings' | 'unassigned' | 'waiting' | 'progress' | 'closed' | 'accepted'

export function matchesFilter(ride: PrototypeRide, filter: DayFilter): boolean {
  if (filter === 'urgent')
    return ride.urgent !== null
  if (filter === 'warnings')
    return ride.warnings.length > 0
  if (filter === 'unassigned')
    return ride.state === 'unassigned'
  if (filter === 'waiting')
    return ride.state === 'assigned'
  if (filter === 'progress')
    return ride.state === 'in-progress'
  if (filter === 'closed')
    return ride.state === 'done' || ride.state === 'no-show' || ride.state === 'cancelled'
  if (filter === 'accepted')
    return ride.state === 'accepted'
  return true
}

export function filterCounts(rides: readonly PrototypeRide[]): Record<DayFilter, number> {
  const filters: DayFilter[] = ['all', 'urgent', 'warnings', 'unassigned', 'waiting', 'progress', 'closed', 'accepted']
  return Object.fromEntries(filters.map(filter => [filter, rides.filter(ride => matchesFilter(ride, filter)).length])) as Record<DayFilter, number>
}

