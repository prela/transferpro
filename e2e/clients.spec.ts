import { expect, test } from '@playwright/test'
import { seedMember, seedTenant } from './fixtures/seed'
import { chooseOption, openAudit, signIn, switchLocale } from './fixtures/ui'

test('admin adds a client, corrects it, and the audit log shows the entries', async ({ page }) => {
  const tenant = await seedTenant('clients-admin')
  await signIn(page, tenant.adminEmail, tenant.password, tenant.name)
  await page.getByRole('link', { name: 'Naručitelji' }).click()
  await expect(page.getByRole('button', { name: tenant.name, exact: true })).toBeVisible()
  await expect(page.getByText('Još nema naručitelja. Dodajte prvog.')).toBeVisible()

  await page.getByRole('button', { name: '+ Dodaj', exact: true }).click()
  let dialog = page.getByRole('dialog')
  await dialog.getByRole('button', { name: 'Odustani', exact: true }).click()
  await expect(dialog).toBeHidden()

  await page.getByRole('button', { name: '+ Dodaj', exact: true }).click()
  dialog = page.getByRole('dialog')
  await dialog.getByRole('button', { name: 'Zatvori', exact: true }).click()
  await expect(dialog).toBeHidden()

  await page.getByRole('button', { name: '+ Dodaj', exact: true }).click()
  dialog = page.getByRole('dialog')
  await dialog.getByLabel('Ime').fill('Ana Kovač')
  await dialog.getByRole('button', { name: 'Dodaj naručitelja', exact: true }).click()
  await expect(dialog.getByRole('alert')).toContainText('Odaberite vrstu: agencija, hotel ili osoba.')

  await dialog.getByLabel('Ime').fill(' ')
  await chooseOption(page, dialog.getByRole('combobox', { name: 'Vrsta' }), 'Hotel')
  await dialog.getByRole('button', { name: 'Dodaj naručitelja', exact: true }).click()
  await expect(dialog.getByRole('alert')).toContainText('Unesite ime.')

  await switchLocale(page, 'en')
  await page.getByRole('button', { name: '+ Add', exact: true }).click()
  dialog = page.getByRole('dialog')
  await dialog.getByLabel('Name').fill(' ')
  await chooseOption(page, dialog.getByRole('combobox', { name: 'Kind' }), 'Hotel')
  await dialog.getByRole('button', { name: 'Add client', exact: true }).click()
  await expect(dialog.getByRole('alert')).toContainText('Enter a name.')

  await switchLocale(page, 'hr')
  await page.getByRole('button', { name: '+ Dodaj', exact: true }).click()
  dialog = page.getByRole('dialog')
  await dialog.getByLabel('Ime').fill('Hotel Adriatic')
  await chooseOption(page, dialog.getByRole('combobox', { name: 'Vrsta' }), 'Hotel')
  await dialog.getByRole('button', { name: 'Dodaj naručitelja', exact: true }).click()
  await expect(dialog).toBeHidden()
  await expect(page.getByRole('button', { name: 'Hotel Adriatic', exact: true })).toBeVisible()

  await page.getByRole('button', { name: 'Hotel Adriatic', exact: true }).click()
  dialog = page.getByRole('dialog')
  await dialog.getByLabel('Ime').fill('Hotel Park')
  await chooseOption(page, dialog.getByRole('combobox', { name: 'Vrsta' }), 'Agencija')
  await dialog.getByRole('button', { name: 'Spremi', exact: true }).click()
  await expect(dialog).toBeHidden()
  await expect(page.getByRole('button', { name: 'Hotel Park', exact: true })).toBeVisible()
  await expect(page.getByRole('cell', { name: 'Agencija' })).toBeVisible()

  await page.getByRole('button', { name: '+ Dodaj', exact: true }).click()
  dialog = page.getByRole('dialog')
  await dialog.getByLabel('Ime').fill('Marko Marić')
  await chooseOption(page, dialog.getByRole('combobox', { name: 'Vrsta' }), 'Osoba')
  await dialog.getByRole('button', { name: 'Dodaj naručitelja', exact: true }).click()
  await expect(dialog).toBeHidden()
  await expect(page.getByRole('button', { name: 'Marko Marić', exact: true })).toBeVisible()
  await expect(page.getByRole('cell', { name: 'Osoba' })).toBeVisible()
  await page.getByRole('searchbox', { name: 'Traži' }).fill('Park')
  await expect(page.getByRole('button', { name: 'Hotel Park', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Marko Marić', exact: true })).toHaveCount(0)
  await page.getByRole('searchbox', { name: 'Traži' }).fill('')
  await expect(page.getByRole('button', { name: 'Marko Marić', exact: true })).toBeVisible()

  // Opening Audit reads the rows this page already wrote.
  await openAudit(page)
  await expect(page.getByRole('cell', { name: 'Klijent dodan', exact: true })).toHaveCount(2)
  await expect(page.getByRole('cell', { name: 'Ime klijenta ispravljeno', exact: true })).toBeVisible()
  await expect(page.getByRole('cell', { name: 'Vrsta klijenta ispravljena', exact: true })).toBeVisible()
  await expect(page.getByRole('cell', { name: 'Osoba', exact: true })).toBeVisible()

  await page.getByRole('link', { name: 'Naručitelji' }).click()
  await expect(page).toHaveURL(/\/clients$/)
  await page.reload()
  await expect(page.getByRole('button', { name: 'Hotel Park', exact: true })).toBeVisible()
  await expect(page.getByRole('cell', { name: 'Agencija' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Marko Marić', exact: true })).toBeVisible()
  await expect(page.getByRole('cell', { name: 'Osoba' })).toBeVisible()
})

test('dispatcher adds a client and the screen shows the tenant name', async ({ page }) => {
  const tenant = await seedTenant('clients-disp')
  const dispatcher = await seedMember(tenant.tenantId, 'dispatcher', 'Dispečer')
  await signIn(page, dispatcher.email, dispatcher.password, tenant.name)
  await page.getByRole('link', { name: 'Naručitelji' }).click()
  await expect(page.getByRole('button', { name: tenant.name, exact: true })).toBeVisible()

  await page.getByRole('button', { name: '+ Dodaj', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('Ime').fill('Agencija Sunce')
  await chooseOption(page, dialog.getByRole('combobox', { name: 'Vrsta' }), 'Agencija')
  await dialog.getByRole('button', { name: 'Dodaj naručitelja', exact: true }).click()
  await expect(dialog).toBeHidden()
  await expect(page.getByRole('button', { name: 'Agencija Sunce', exact: true })).toBeVisible()
})
